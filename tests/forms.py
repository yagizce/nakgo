"""Form taslağı, açık kayıt sınırı ve mazot hesabı tarayıcı regresyonları."""

from datetime import datetime, timezone, timedelta

def run_forms(page, check):
    p=page()
    # Liste çizimi büyük yy2 kaydını serileştirmemeli.
    p.evaluate("window.__dataCalls=0;window.__stringify=JSON.stringify;JSON.stringify=(value,...args)=>{if(value&&value.loads===loads&&value.offers===offers)window.__dataCalls++;return window.__stringify(value,...args)}")
    p.fill('#q','Ankara');p.fill('#q','')
    p.click('nav [data-t=me]');p.click('nav [data-t=list]')
    check('arama ve sekme geçişleri ana kaydı serileştirmez',p.evaluate('window.__dataCalls===0'))
    p.evaluate('JSON.stringify=window.__stringify;void 0')
    favorite=p.locator('[data-fav]').first.get_attribute('data-fav')
    p.locator('[data-fav]').first.click();p.reload()
    check('favori render yan etkisi olmadan yenilemede korunur',p.evaluate('(id)=>favs.includes(id)',favorite))
    # Kayıt başarısız olunca işlem sonucunu ve kartı değiştirme.
    p.evaluate("window.__setItem=Storage.prototype.setItem;window.__setItem=window.__setItem||Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('full','QuotaExceededError')};void 0")
    p.locator('[data-fav="'+favorite+'"]').click()
    check('favori kaldırma hatasında kayıt ve seçili durum korunur',p.evaluate('(id)=>favs.includes(id)',favorite) and p.get_attribute('[data-fav="'+favorite+'"]','aria-pressed')=='true')
    p.evaluate('Storage.prototype.setItem=window.__setItem;void 0')
    p.click('nav [data-t=post]');p.click('[data-pm=load]');p.click('#post-next')
    p.fill('#c','Taslak yük');p.fill('#w','0.5');p.fill('#d',datetime.now(timezone(timedelta(hours=3))).strftime('%d.%m.%Y'))
    check('ondalıklı tonaj formda geçerlidir',p.locator('#w').evaluate('e=>e.validity.valid'))
    p.click('#post-next');p.fill('#n','Korunan not')
    p.click('#addit');p.fill('[data-in]','Palet');p.fill('[data-iq]','-1');p.click('#go')
    check('negatif kalem miktarı yayınlanmaz',p.is_visible('#go') and p.evaluate("!loads.some(l=>l.cargo==='Taslak yük')"))
    p.fill('[data-iq]','2')
    p.evaluate("window.__setItem=window.__setItem||Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('full','QuotaExceededError')};void 0")
    p.fill('#n','Henüz cihazda saklanmayan not')
    check('taslak hatası kalıcı durum satırında doğru görünür',p.inner_text('.draft-state')=='Taslak kaydedilemedi')
    p.click('[data-pm=truck]')
    check('boş araç formu yük fotoğrafı taşımıyor',p.evaluate("postImg===''&&getPostDrafts().truck.image===''"))
    p.click('[data-pm=load]')
    check('depo doluyken form değişimi yazılanları bellekte korur',p.input_value('#n')=='Henüz cihazda saklanmayan not' and p.input_value('[data-iq]')=='2')
    p.evaluate('Storage.prototype.setItem=window.__setItem;void 0')
    p.fill('#n','Artık kaydedilen not')
    check('depolama düzelince taslak durumu yenilenir',p.inner_text('.draft-state')=='Taslak kaydedildi')
    p.reload();p.click('nav [data-t=post]')
    check('taslak adımı ve kalemleri yenilemeden sonra korunur',p.is_visible('#go') and p.input_value('#n')=='Artık kaydedilen not' and p.input_value('[data-iq]')=='2')
    # Fotoğraf işlenirken başka form açılması deterministik olarak canlandırılır.
    p.evaluate('window.__pickImg=pickImg;pickImg=callback=>{window.__photoReady=callback};void 0')
    p.click('#ph');p.click('[data-pm=truck]');p.evaluate("window.__photoReady('data:image/jpeg;base64,AAAA');pickImg=window.__pickImg;void 0")
    check('geç tamamlanan yük fotoğrafı araç taslağına yazılmaz',p.evaluate("postImg===''&&getPostDrafts().truck.image===''"))
    p.click('[data-pm=load]');p.click('#go');p.reload()
    check('geçerli kalemli yük kalıcı yayınlanır',p.evaluate("loads.some(l=>l.cargo==='Taslak yük'&&l.ton===.5&&l.items[0].q===2)"))
    check('yayınlanan yük taslağı temizlenir',p.evaluate("!getPostDrafts().load"))
    # Kaydetmeden geri çekme ve sahte başarı bildirimi oluşmamalı.
    p.evaluate("offers=[{...loads.find(l=>l.id===2),status:'wait',loadId:2,bidder:'',ots:Date.now(),stage:0}];save();tab='mine';setNav();render()")
    p.evaluate("window.__setItem=window.__setItem||Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('full','QuotaExceededError')};void 0")
    p.click('[data-c="2"]')
    check('iş geri çekme hatası ekranda işi tutar',p.locator('[data-c="2"]').count()==1 and 'Kaydedilemedi' in p.inner_text('#toast'))
    p.evaluate('Storage.prototype.setItem=window.__setItem;void 0');p.click('[data-c="2"]');p.reload()
    check('başarılı iş geri çekme yenilemede korunur',p.evaluate('offers.length===0'))
    p.click('nav [data-t=me]');p.click('#profile-fuel')
    p.fill('#calc-km','500');p.fill('#calc-fuel','50');p.fill('#calc-cons','30')
    old=p.inner_text('#res');km=p.input_value('#calc-km');back=p.is_checked('#bk')
    p.evaluate("window.__setItem=window.__setItem||Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('full','QuotaExceededError')};void 0")
    p.fill('#calc-km','700')
    check('mazot kayıt hatasında girdi ve sonuç aynı eski değeri gösterir',p.input_value('#calc-km')==km and p.inner_text('#res')==old)
    p.click('#bk')
    check('mazot dönüş seçimi kaydedilemezse geri alınır',p.is_checked('#bk')==back and p.inner_text('#res')==old)
    p.evaluate('Storage.prototype.setItem=window.__setItem;void 0');p.fill('#calc-km','1e308')
    check('mazot hesabı taşan sayıyı reddeder',p.input_value('#calc-km')==km and p.inner_text('#res')==old)
    p.fill('#calc-km','600');p.click('#cx');p.reload();p.click('nav [data-t=me]');p.click('#profile-fuel')
    check('geçerli mazot değişikliği yeniden açılınca korunur',p.input_value('#calc-km')=='600')
    p.context.close()

    # Bozuk seçenekler, başka alanları kaybetmeden geçerli varsayılana döner.
    p=page()
    p.evaluate("""localStorage.setItem('ng-post-drafts',JSON.stringify({load:{step:2,fields:{f:'Olmayan şehir',t:'Ankara',v:'Eski araç',b:'Eski kasa',d:'Eski gün',c:'Korunan yük',w:'2',n:'Korunan açıklama'},items:[{n:'Koli',q:'2',u:'Eski birim'}]}}))""")
    p.reload();p.click('nav [data-t=post]');p.click('[data-pm=load]')
    check('eski taslakta kaldırılmış seçenekler formu kilitlemez',p.evaluate("cities.includes(document.querySelector('#f').value)&&vehicles.includes(document.querySelector('#v').value)&&bodies.includes(document.querySelector('#b').value)&&document.querySelector('#d').value==='Eski gün'"))
    check('eski taslağın geçerli metinleri korunur',p.input_value('#c')=='Korunan yük' and p.input_value('#n')=='Korunan açıklama')
    p.click('#go');check('geçersiz eski tarih kullanıcı düzeltmeden yayınlanmaz',p.is_visible('#go') and p.evaluate("!loads.some(l=>l.cargo==='Korunan yük')"))
    p.fill('#d',datetime.now(timezone(timedelta(hours=3))).strftime('%d.%m.%Y'));p.click('#go');check('kullanıcının düzelttiği taslak yayınlanabilir',p.evaluate("loads.some(l=>l.cargo==='Korunan yük')&&tab==='list'"))
    p.context.close()
